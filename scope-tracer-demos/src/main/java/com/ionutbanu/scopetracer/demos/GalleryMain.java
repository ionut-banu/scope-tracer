package com.ionutbanu.scopetracer.demos;

import com.ionutbanu.scopetracer.analyzer.HtmlRenderer;
import com.ionutbanu.scopetracer.analyzer.JfrParser;
import com.ionutbanu.scopetracer.analyzer.model.TraceModel;
import java.io.IOException;
import java.io.OutputStream;
import java.io.PrintStream;
import java.lang.management.ManagementFactory;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.ArrayList;
import java.util.LinkedHashMap;
import java.util.List;
import java.util.Map;
import jdk.jfr.Recording;

/**
 * Regenerates the gallery: records every scenario of {@link GalleryCatalog} with {@code
 * TracedScope}, checks each recording against the shape the scenario declares, and writes {@code
 * docs/gallery/index.html}, {@code docs/gallery/reports/*.html} and {@code
 * docs/example/order-processing-report.html}. With {@code --check} it writes nothing and exits 1
 * when what is committed no longer matches what the JDK and the renderer produce.
 *
 * <p>Run from the repository root (setup for {@code $JARS}: "Run a demo" under "Demos" in {@code
 * README.md}):
 *
 * <pre>{@code
 * java --enable-preview -cp "$JARS" com.ionutbanu.scopetracer.demos.GalleryMain
 * java --enable-preview -cp "$JARS" com.ionutbanu.scopetracer.demos.GalleryMain --check
 * }</pre>
 *
 * <p>Never with the agent: every event would be emitted twice. The command refuses to run under a
 * scope-tracer {@code -javaagent}.
 *
 * <p>A recording that does not show the behaviour its scenario was written to show (a task that
 * lost a race, a fork with no completion) is recorded again, at most {@value #ATTEMPTS} times in
 * all, and then the command exits 1 naming the scenario, the shape it expected and the one it got,
 * without writing anything.
 */
public final class GalleryMain {

  static final int ATTEMPTS = 3;

  /** The text at the top of the example report; inserted by this command, not by the renderer. */
  static final String BANNER =
      """
      <div style="background:#1565c0;color:#fff;margin:-2rem -2rem 1.5rem;padding:0.9rem 2rem;font-size:0.85rem;line-height:1.5;">
        This is an example report generated by <a href="https://github.com/ionut-banu/scope-tracer" style="color:#fff;font-weight:bold;">scope-tracer</a>
        from the <code style="background:rgba(255,255,255,0.15);padding:0.1rem 0.35rem;border-radius:3px;">OrderProcessingDemo</code>
        — a nested e-commerce order pipeline where one order is declined by a fraud check.
        It shows nested scopes, cancellation propagation, and critical-path highlighting. No install needed — this file is
        self-contained HTML generated straight from a JFR recording.
        See the <a href="https://github.com/ionut-banu/scope-tracer#readme" style="color:#fff;">README</a> to generate your own.
      </div>
      """;

  private static final String PAGE_FILE = "docs/gallery/index.html";

  private GalleryMain() {}

  /** Records scenarios; replaced in tests, so the logic around it needs no JVM and no clock. */
  interface Recorder {
    /** Runs the scenario once, unrecorded, so classes are loaded before it is timed. */
    void warmUp(GalleryScenario scenario) throws Exception;

    /** Runs the scenario under a recording and returns what the recording holds. */
    TraceModel record(GalleryScenario scenario) throws Exception;
  }

  public static void main(String[] args) throws Exception {
    boolean check = false;
    for (var arg : args) {
      if (arg.equals("--check")) {
        check = true;
      } else {
        System.err.println("usage: GalleryMain [--check]");
        System.exit(2);
      }
    }
    var agent = scopeTracerAgent(ManagementFactory.getRuntimeMXBean().getInputArguments());
    if (agent != null) {
      System.err.println(
          "GalleryMain records with TracedScope and must not run with the agent ("
              + agent
              + "): every event would be emitted twice. Run it without -javaagent.");
      System.exit(1);
    }
    System.exit(
        run(Path.of(""), check, GalleryCatalog.ALL, new JfrRecorder(), System.out, System.err));
  }

  /** The {@code -javaagent} argument that loads a scope-tracer agent, or null. */
  static String scopeTracerAgent(List<String> jvmArguments) {
    return jvmArguments.stream()
        .filter(a -> a.startsWith("-javaagent:") && a.contains("scope-tracer"))
        .findFirst()
        .orElse(null);
  }

  /**
   * The whole command. Returns the exit code: 0 on success, 1 when the gate rejects a scenario, a
   * file differs (with {@code check}) or the working directory is not the repository root.
   */
  static int run(
      Path root,
      boolean check,
      List<GalleryScenario> scenarios,
      Recorder recorder,
      PrintStream out,
      PrintStream err)
      throws Exception {
    if (!Files.isDirectory(root.resolve("docs"))
        || !Files.isRegularFile(root.resolve(scenarios.get(0).sourceFile()))) {
      err.println("no docs/ directory here: run it from the repository root");
      return 1;
    }
    for (var scenario : scenarios) {
      recorder.warmUp(scenario);
    }
    // Everything is generated in memory first, so a scenario that cannot be recorded leaves the
    // committed files as they were.
    var files = new LinkedHashMap<String, String>();
    for (var scenario : scenarios) {
      var html = recordWithGate(scenario, recorder, out, err);
      if (html == null) return 1;
      files.put(scenario.reportFile(), scenario.banner() ? withBanner(html) : html);
    }
    var page = GalleryPage.render(root, scenarios);
    files.put(PAGE_FILE, page);

    return check ? compare(root, files, out, err) : write(root, files, out);
  }

  private static String recordWithGate(
      GalleryScenario scenario, Recorder recorder, PrintStream out, PrintStream err)
      throws Exception {
    List<String> problems = List.of();
    TraceModel last = null;
    for (int attempt = 1; attempt <= ATTEMPTS; attempt++) {
      last = recorder.record(scenario);
      problems = scenario.shape().problems(last);
      if (problems.isEmpty()) {
        out.println(scenario.id() + ": recorded on attempt " + attempt);
        return HtmlRenderer.render(last);
      }
      out.println(
          scenario.id() + ": attempt " + attempt + " rejected: " + String.join("; ", problems));
    }
    err.println(
        "scenario " + scenario.id() + " did not show its shape in " + ATTEMPTS + " attempts");
    err.println("  expected: " + scenario.shape().describeExpected());
    err.println("  actual:   " + Shape.describe(Shape.observe(last)));
    err.println("  problems: " + String.join("; ", problems));
    err.println("nothing was written");
    return null;
  }

  /** The report with the banner after {@code <body>}; the renderer does not write it. */
  static String withBanner(String html) {
    var body = "<body>\n";
    int at = html.indexOf(body);
    if (at < 0) throw new IllegalStateException("the report has no <body> line");
    int end = at + body.length();
    return html.substring(0, end) + BANNER + html.substring(end);
  }

  private static int write(Path root, Map<String, String> files, PrintStream out)
      throws IOException {
    for (var file : files.entrySet()) {
      var path = root.resolve(file.getKey());
      Files.createDirectories(path.getParent());
      Files.writeString(path, file.getValue(), StandardCharsets.UTF_8);
      out.println("wrote " + file.getKey() + " (" + file.getValue().length() + " chars)");
    }
    return 0;
  }

  private static int compare(
      Path root, Map<String, String> regenerated, PrintStream out, PrintStream err)
      throws IOException {
    var differing = new ArrayList<String>();
    for (var file : regenerated.entrySet()) {
      var path = root.resolve(file.getKey());
      if (!Files.isRegularFile(path)) {
        differing.add(file.getKey());
        err.println(file.getKey() + ": missing");
        continue;
      }
      var committed = Files.readString(path, StandardCharsets.UTF_8);
      String difference;
      if (file.getKey().equals(PAGE_FILE)) {
        // The page holds no time: it must be identical.
        difference = committed.equals(file.getValue()) ? null : "the page text differs";
      } else {
        difference = ReportSkeleton.firstDifference(committed, file.getValue());
      }
      if (difference == null) {
        out.println(file.getKey() + ": ok");
      } else {
        differing.add(file.getKey());
        err.println(file.getKey() + ": differs (" + difference + ")");
      }
    }
    if (differing.isEmpty()) return 0;
    err.println(
        "The gallery is out of date: "
            + String.join(", ", differing)
            + ". Run GalleryMain without --check from the repository root and commit the result.");
    return 1;
  }

  /** Runs a scenario with its own printing (the order demo prints a line per step) held back. */
  private static void runQuietly(GalleryScenario scenario) throws Exception {
    var original = System.out;
    System.setOut(new PrintStream(OutputStream.nullOutputStream(), false, StandardCharsets.UTF_8));
    try {
      scenario.body().run();
    } finally {
      System.setOut(original);
    }
  }

  /** Records in this JVM, with a JFR recording of the scope-tracer events only. */
  static final class JfrRecorder implements Recorder {

    @Override
    public void warmUp(GalleryScenario scenario) throws Exception {
      runQuietly(scenario);
    }

    @Override
    public TraceModel record(GalleryScenario scenario) throws Exception {
      var jfr = Files.createTempFile("scope-tracer-gallery-", ".jfr");
      try (var recording = new Recording()) {
        recording.enable("com.ionutbanu.scopetracer.*");
        recording.start();
        try {
          runQuietly(scenario);
        } finally {
          recording.stop();
        }
        recording.dump(jfr);
        return JfrParser.parse(jfr);
      } finally {
        Files.deleteIfExists(jfr);
      }
    }
  }
}
